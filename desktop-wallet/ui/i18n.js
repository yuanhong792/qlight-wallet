/* ------------------------------------------------------------------ 基础设施 */

let LANG = detectLang();

/** 系统语言 → 支持列表里最合适的一项 */
function detectLang() {
  const saved = localStorage.getItem("qlight.lang");
  const supported = LANGS.map(([, code]) => code);
  if (saved && supported.includes(saved)) return saved;
  for (const cand of navigator.languages || [navigator.language]) {
    const c = cand.toLowerCase();
    const hit = supported.find((code) => c === code.toLowerCase() || c.startsWith(code.toLowerCase()));
    if (hit) return hit;
  }
  return "en";
}

/** 最近回退链：当前语言 → 英文 → 简中 → key 本身 */
function t(key, params = {}) {
  let s = I18N[LANG] && I18N[LANG][key];
  if (s == null) s = I18N.en[key];
  if (s == null) s = I18N["zh-CN"][key];
  if (s == null) s = key;
  for (const [k, v] of Object.entries(params)) {
    s = s.replaceAll(`{${k}}`, v);
  }
  return s;
}

/** 语言菜单（母语名，WIDTH 固定）。发现 applyI18n 被调用即同步选中项 */
function syncLangControl() {
  const sel = document.getElementById("lang-select");
  if (!sel) return;
  if (!sel.options.length) {
    sel.innerHTML = LANGS.map(([code, name]) => `<option value="${code}">${name}</option>`).join("");
  }
  sel.value = LANG;
}

/** 扫描并应用静态词条 */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.documentElement.lang = LANG;
  document.title = t("app.title");
  syncLangControl();
}

/** 切换语言并重写动态区 */
function setLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  localStorage.setItem("qlight.lang", lang);
  applyI18n();
  if (window.refreshAll) window.refreshAll();
}
